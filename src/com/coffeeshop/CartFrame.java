    private void loadCart() {

    model.setRowCount(0);

    for (CartItem item : Cart.items) {

        model.addRow(new Object[]{
            item.getName(),
            item.getQuantity(),
            "₹" + String.format("%.2f", item.getPrice()),
            "₹" + String.format("%.2f", item.getTotal())
        });
    }

    jLabel2.setText(
            "TOTAL: ₹" +
            String.format("%.2f", Cart.getTotal())
    );
}
